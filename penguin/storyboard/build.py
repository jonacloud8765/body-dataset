#!/usr/bin/env python3
"""Resolve the shot list against the measured song.

Reads shots.yaml and ../analysis/song-map.json and writes:
  timeline.json                    every shot with start/end in seconds and frames (for Remotion)
  ../../docs/penguin/shotlist.md   the shot list section of the pre-production document

A shot starts at its `at` (bar.beat on the song grid, or "<seconds>s") and ends where the next
shot starts. The build fails if shots run backwards, overlap, or are shorter than 12 frames.
"""
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
MIN_FRAMES = 12


def load():
    song = json.loads((HERE.parent / "analysis" / "song-map.json").read_text())
    shots = yaml.safe_load((HERE / "shots.yaml").read_text())
    return song, shots


def resolve(pos, grid):
    """'2.3.5' -> bar 2, beat 3.5 on the grid; '139.0s' -> 139.0 seconds."""
    pos = str(pos)
    if pos.endswith("s"):
        return float(pos[:-1])
    bar, *rest = pos.split(".")
    beat = float(".".join(rest)) if rest else 1.0
    return grid["first_bar_s"] + ((int(bar) - 1) * 4 + (beat - 1)) * grid["beat_s"]


def mmss(t):
    m, s = divmod(t, 60)
    return f"{int(m)}:{s:05.2f}"


def barbeat(t, grid, song_end=None):
    """Seconds -> 'bar.beat' ('2.3.5' = bar 2, beat 3.5). '—' before bar 1 or after the song."""
    if song_end is not None and t > song_end + 1e-3:
        return "after song"
    x = round((t - grid["first_bar_s"]) / grid["beat_s"], 3)
    if x < 0:
        return "—"
    bar, beat = int(x // 4) + 1, round(x % 4 + 1, 2)
    return f"{bar}.{beat:g}"


def sung(start, end, lines):
    out = []
    for ln in lines:
        a, b = ln["start"]["t"], ln["end"]["t"]
        if min(b, end) - max(a, start) > 0.15:
            text = ln["text"]
            if a < start - 0.15:
                text = "…" + text
            if b > end + 0.15:
                text = text + "…"
            out.append(text)
    return out


def main():
    song, shots = load()
    grid, fps = song["grid"], song["grid"]["fps"]
    song_end = song["source"]["duration_s"]
    errors = []
    for i, s in enumerate(shots):
        s["start_s"] = resolve(s["at"], grid)
        nxt = shots[i + 1]["at"] if i + 1 < len(shots) else s.get("end")
        if nxt is None:
            errors.append(f"{s['id']}: last shot needs an `end`")
            continue
        s["end_s"] = resolve(nxt, grid)
    for s in shots:
        s["from"] = 0 if s["start_s"] <= 0.0 else int(round(s["start_s"] * fps))
        s["to"] = int(round(s["end_s"] * fps))
        s["frames"] = s["to"] - s["from"]
        s["dur_s"] = s["end_s"] - s["start_s"]
        if s["frames"] < MIN_FRAMES:
            errors.append(f"{s['id']}: only {s['frames']} frames")
        for b in s.get("beats") or []:
            t = resolve(b["at"], grid)
            if not (s["start_s"] - 1e-6 <= t < s["end_s"] + 1e-6):
                errors.append(f"{s['id']}: beat {b['at']} ({t:.2f}s) is outside the shot")
            b["t"] = round(t, 3)
            b["frame"] = int(round(t * fps)) - s["from"]
        s["sung"] = sung(s["start_s"], s["end_s"], song["lines"])
    if errors:
        sys.exit("\n".join(errors))

    total = shots[-1]["to"]
    (HERE / "timeline.json").write_text(json.dumps({
        "fps": fps, "width": 1920, "height": 1080, "durationInFrames": total,
        "songEndFrame": int(round(song["source"]["duration_s"] * fps)),
        "shots": [{k: v for k, v in s.items() if k not in ("at",)} | {"at": str(s["at"])}
                  for s in shots]}, indent=1))

    md = []
    md.append("<!-- Generated by penguin/storyboard/build.py from shots.yaml and song-map.json. "
              "Edit those, not this file. -->\n")
    md.append(f"**{len(shots)} shots · {mmss(total / fps)} · {total} frames at {fps} fps** "
              f"(song {mmss(song['source']['duration_s'])} + silent epilogue). "
              "Bar.beat is the shot's first frame on the song grid.\n")
    md.append("### 12.1 Overview\n")
    md.append("| Shot | Title | Start | Dur | Bar.beat | Section | Sung | Mode | Int. | Framing · move |")
    md.append("|---|---|---|---|---|---|---|---|---|---|")
    names = {x["id"]: x["name"] for x in song["sections"]}
    names["epilogue"] = "Epilogue"
    for s in shots:
        lyric = " / ".join(s["sung"]) if s["sung"] else "—"
        md.append(f"| **{s['id']}** | {s['title']} | {mmss(s['start_s'])} | {s['dur_s']:.2f} s | "
                  f"{barbeat(s['start_s'], grid, song_end)} | {names.get(s['section'], s['section'])} | {lyric} | "
                  f"{s['mode']} | {s['intensity'] or '—'} | {s['framing']} · {s['move']} |")
    md.append("")
    md.append("### 12.2 Shot cards\n")
    md.append("Every shot, with every field. Times are song time. *Beats* are events inside the "
              "shot, placed on the grid.\n")
    current = None
    for s in shots:
        sec = names.get(s["section"], s["section"])
        if sec != current:
            md.append(f"#### {sec}\n")
            current = sec
        md.append(f"##### {s['id']} · {s['title']}")
        md.append(f"`{mmss(s['start_s'])} – {mmss(s['end_s'])}` · {s['dur_s']:.2f} s · "
                  f"frames {s['from']}–{s['to'] - 1} · bar {barbeat(s['start_s'], grid, song_end)} · "
                  f"{s['mode']} · intensity {str(s['intensity']) + '/5' if s['intensity'] else '— (no music)'}\n")
        rows = [
            ("Sung", " / ".join(f"“{x}”" for x in s["sung"]) or "—"),
            ("Music", s["music"]),
            ("Visual", s["visual"]),
            ("Character", s["action"]),
            ("Head · lip sync", f"{s['head']} · {'sings' if s['sing'] else 'silent'}"
             if s["head"] != "none" else ("—" if not s["sing"] else "sings")),
            ("Framing", s["framing"]),
            ("Camera", s["move"]),
            ("Environment", s["environment"]),
            ("Lighting", s["light"]),
            ("Color", s["color"]),
            ("Animation", s["animation"]),
            ("Effects", s["fx"]),
            ("Transition out", s["out"]),
            ("Purpose", s["purpose"]),
            ("Mountain", s["stage"] + (f" · Refrain {s['refrain']}" if s.get("refrain") else "")),
        ]
        if s.get("lower_third"):
            rows.append(("Lower third", " / ".join(f"`{x}`" for x in s["lower_third"])))
        if s.get("counter"):
            c = s["counter"]
            rows.append(("Counters", f"DAY {c['day'][0]}→{c['day'][1]}, {c['km'][0]}→{c['km'][1]} KM"))
        if s.get("beats"):
            rows.append(("Beats", "; ".join(
                f"{barbeat(b['t'], grid) if not str(b['at']).endswith('s') else mmss(b['t'])}: {b['do']}"
                for b in s["beats"])))
        for k, v in rows:
            md.append(f"- **{k}:** {v}")
        md.append("")
    out = ROOT / "docs" / "penguin" / "shotlist.md"
    out.write_text("\n".join(md))

    # keep the overview table in the main document in sync
    doc = ROOT / "docs" / "penguin" / "preproduction.md"
    if doc.exists():
        text = doc.read_text()
        a, b = "<!-- shotlist:begin -->", "<!-- shotlist:end -->"
        if a in text and b in text:
            start = md.index("### 12.1 Overview\n")
            end = md.index("### 12.2 Shot cards\n")
            table = "\n".join(x for x in md[start + 1:end] if x.strip())
            head, rest = text.split(a, 1)
            _, tail = rest.split(b, 1)
            doc.write_text(head + a + "\n" + table + "\n" + b + tail)

    by_sec = {}
    for s in shots:
        by_sec.setdefault(names.get(s["section"], s["section"]), []).append(s["dur_s"])
    print(f"{len(shots)} shots, {total} frames ({mmss(total / fps)})")
    for k, v in by_sec.items():
        print(f"  {k:20s} {len(v):2d} shots, avg {sum(v) / len(v):.2f} s, min {min(v):.2f} s")
    print(f"wrote {HERE / 'timeline.json'} and {out}")


if __name__ == "__main__":
    main()
